<?php
declare(strict_types=1);
$dsn = (string) getenv('TAREFAS_TEST_DSN');
if (!str_contains($dsn, 'host=127.0.0.1') || !str_contains($dsn, 'dbname=automacao_teste')) throw new RuntimeException('Use apenas o banco local descartável.');
$db = new PDO($dsn, (string) getenv('TAREFAS_TEST_USER'), (string) getenv('TAREFAS_TEST_PASS'), [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$executar = static function (string $modo, ?int $id = null): string {
    $env = getenv();
    $env['TAREFAS_TEST_PAGE_MODE'] = $modo;
    if ($id !== null) $env['TAREFAS_TEST_RULE_ID'] = (string) $id;
    $processo = proc_open([PHP_BINARY, __DIR__ . '/cartorio-tarefas-rules-page.php'], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, null, $env);
    if (!is_resource($processo)) throw new RuntimeException('Não foi possível iniciar o harness.');
    $saida = stream_get_contents($pipes[1]);
    $erro = stream_get_contents($pipes[2]);
    fclose($pipes[1]); fclose($pipes[2]);
    if (proc_close($processo) !== 0) throw new RuntimeException('Página falhou: ' . $erro);
    return $saida;
};
if (!str_contains($executar('operacional'), 'Acesso restrito')) throw new RuntimeException('Usuário operacional acessou a administração.');
if (!str_contains($executar('csrf'), 'Sua sessão expirou')) throw new RuntimeException('Um token inválido não foi rejeitado.');
$executar('salvar');
$st = $db->prepare('SELECT id, ativa FROM cartorio_tarefas_regras WHERE nome = ? ORDER BY id DESC LIMIT 1');
$st->execute(['Regra de teste da página']);
$regra = $st->fetch(PDO::FETCH_ASSOC);
if (!$regra || !(int) $regra['ativa']) throw new RuntimeException('A página não salvou a regra ativa.');
$id = (int) $regra['id'];
$html = $executar('editar', $id);
if (!str_contains($html, 'Editar regra') || !str_contains($html, 'Regra de teste da página') || !str_contains($html, 'id="regra-acoes"')) throw new RuntimeException('A página não carregou a regra para edição.');
$executar('alternar', $id);
$st->execute(['Regra de teste da página']);
if ((int) $st->fetch(PDO::FETCH_ASSOC)['ativa'] !== 0) throw new RuntimeException('A página não desativou a regra.');
echo "Administração, edição, CSRF e acesso verificados.\n";
